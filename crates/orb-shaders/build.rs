//! Reflects the scene tables' structs in `types.wgsl` and the shaders'
//! uniforms with naga: their layouts for Rust (`layout.rs`), so Rust never
//! mirrors them by hand. With the `ir` feature, also writes each shader's
//! naga modules (`ir.rs`); with `glsl`, WebGL 2's stages as GLSL ES 3.00
//! (`glsl.rs`).

fn main() {
    println!("cargo::rerun-if-changed=src/catalog.rs");
    println!("cargo::rerun-if-changed=src/split.rs");
    println!("cargo::rerun-if-changed=src/wgsl");
    // Each shader parsed once, for both the reflection and the split.
    let modules: Vec<(&str, naga::Module)> = catalog::SHADERS
        .iter()
        .map(|shader| {
            let source = shader.source();
            let module = naga::front::wgsl::parse_str(&source)
                .unwrap_or_else(|e| panic!("{}: {}", shader.label, e.emit_to_string(&source)));
            (shader.label, module)
        })
        .collect();
    reflect::write(&modules);
    strip();
    let wasm = std::env::var("CARGO_CFG_TARGET_ARCH").is_ok_and(|a| a == "wasm32");
    if wasm && std::env::var_os("CARGO_FEATURE_GLSL").is_none() {
        minify::write(&modules);
    }
    entries(&modules, std::env::var_os("CARGO_FEATURE_IR").is_some());
    // `glsl_only`: WebGL 2's web build (core-gl.wasm), whose pipelines
    // compile the GLSL written here, carries no WGSL.
    println!("cargo::rustc-check-cfg=cfg(glsl_only)");
    if std::env::var_os("CARGO_FEATURE_GLSL").is_some() {
        glsl::write();
        if std::env::var("CARGO_CFG_TARGET_ARCH").is_ok_and(|a| a == "wasm32") {
            println!("cargo::rustc-cfg=glsl_only");
        }
    }
}

/// Writes every WebGL 2 stage as GLSL ES 3.00, as wgpu's GL back end would
/// write it, so a GL device compiles the build's GLSL rather than
/// translate WGSL on every load (#140). A stage is written once for every
/// pipeline: its override constants are GLSL constants at their defaults,
/// whose values `glsl()` writes in (`Glsl`), and its depth is clipped from
/// 0 to 1 (`EXT_clip_control`; `glsl()` remaps it where the device can't).
/// Comment lines name each uniform block's and texture's binding, which
/// GLSL ES 3.00 can't say (wgpu-hal's passthrough binding lines).
///
/// Stages share most of their lines (types, helpers), so the lines are kept
/// once, trimmed, in `glsl.txt`, and each stage is its lines' numbers in
/// `glsl.ids` (`u16`s); `glsl.rs` gives each stage's numbers and where its
/// constants are.
mod glsl {
    use std::fmt::Write;

    use naga::back::glsl;

    pub(crate) fn write() {
        let dir = std::env::var("OUT_DIR").expect("cargo sets OUT_DIR");
        let mut lines: std::collections::HashMap<String, u16> = Default::default();
        let mut text = String::new();
        let mut ids: Vec<u8> = Vec::new();
        // Shaders that compose the same modules write the same stages:
        // each is kept once.
        let mut kept: std::collections::HashMap<Vec<u8>, usize> = Default::default();
        let mut rust =
            String::from("// Generated by build.rs.\nconst STAGES: &[(&str, &[Stage])] = &[\n");
        for shader in super::catalog::SHADERS {
            let Some(source) = shader.gl_source() else {
                continue;
            };
            let source = generated(source, &dir);
            let module = naga::front::wgsl::parse_str(&source)
                .unwrap_or_else(|e| panic!("{}: {}", shader.label, e.emit_to_string(&source)));
            writeln!(rust, "    ({:?}, &[", shader.label).unwrap();
            for (entry, one) in super::split::entry_modules(&module) {
                let (stage, constants) = write_stage(shader.label, &entry, one);
                let mut at = Vec::new();
                let mut stage_ids = Vec::new();
                for (n, line) in stage
                    .lines()
                    .map(str::trim)
                    .filter(|l| !l.is_empty())
                    .enumerate()
                {
                    if let Some(name) = constants.iter().find(|c| is_constant(line, c)) {
                        at.push((name.clone(), n));
                    }
                    let next = u16::try_from(lines.len()).expect("fewer than 65536 lines");
                    let id = *lines.entry(line.to_owned()).or_insert_with(|| {
                        text.push_str(line);
                        text.push('\n');
                        next
                    });
                    stage_ids.extend(id.to_le_bytes());
                }
                assert_eq!(
                    at.len(),
                    constants.len(),
                    "{} {entry}: a constant per override",
                    shader.label
                );
                let count = stage_ids.len() / 2;
                let start = *kept.entry(stage_ids).or_insert_with_key(|stage_ids| {
                    ids.extend_from_slice(stage_ids);
                    ids.len() / 2 - count
                });
                writeln!(
                    rust,
                    "        Stage {{ entry: {entry:?}, lines: {start}..{}, constants: &{at:?} }},",
                    start + count
                )
                .unwrap();
            }
            rust.push_str("    ]),\n");
        }
        rust.push_str("];\n");
        std::fs::write(format!("{dir}/glsl.txt"), text).expect("writes OUT_DIR/glsl.txt");
        std::fs::write(format!("{dir}/glsl.ids"), ids).expect("writes OUT_DIR/glsl.ids");
        std::fs::write(format!("{dir}/glsl.rs"), rust).expect("writes OUT_DIR/glsl.rs");
    }

    /// Whether `line` declares the constant an override `name` became.
    fn is_constant(line: &str, name: &str) -> bool {
        let mut words = line.split_ascii_whitespace();
        words.next() == Some("const")
            && words
                .nth(1)
                .is_some_and(|n| n.trim_end_matches('_') == name)
            && words.next() == Some("=")
    }

    /// `source` with the modules this script wrote in place of their
    /// markers (the build's `generated!`).
    fn generated(source: String, dir: &str) -> String {
        let mut out = source;
        while let Some(at) = out.find(super::GENERATED) {
            let rest = &out[at + super::GENERATED.len()..];
            let end = rest.find('\n').expect("a marker's line");
            let name = &rest[..end];
            let path = format!("{dir}/wgsl/{name}.wgsl");
            let module = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{path}: {e}"));
            out.replace_range(at..at + super::GENERATED.len() + end, &module);
        }
        out
    }

    /// One entry point's module as GLSL, with its binding lines, and the
    /// names of the constants its overrides became.
    fn write_stage(label: &str, entry: &str, mut one: naga::Module) -> (String, Vec<String>) {
        let constants = overrides_as_constants(&mut one);
        let validate = |module: &naga::Module| {
            naga::valid::Validator::new(
                naga::valid::ValidationFlags::all(),
                naga::valid::Capabilities::empty(),
            )
            .validate(module)
            .unwrap_or_else(|e| panic!("{label} {entry}: {e}"))
        };
        let mut info = validate(&one);
        let stage = one.entry_points[0].stage;
        // No struct values in a fragment stage, as wgpu's GL back end
        // writes them: drivers that evaluate struct members at the stage's
        // default precision (the Adreno 619's under ANGLE) would read each
        // at `mediump` (`naga::back::glsl::flatten_structs`).
        if stage == naga::ShaderStage::Fragment {
            let flat = glsl::flatten_structs(&one, &info)
                .unwrap_or_else(|e| panic!("{label} {entry}: {e}"));
            info = validate(&flat);
            one = flat;
        }
        let options = glsl::Options {
            version: glsl::Version::Embedded {
                version: 300,
                is_webgl: true,
            },
            // As wgpu's GL back end writes them for an ES context with clip
            // control.
            writer_flags: glsl::WriterFlags::ADJUST_COORDINATE_SPACE
                | glsl::WriterFlags::ZERO_TO_ONE_DEPTH
                | glsl::WriterFlags::FORCE_POINT_SIZE,
            binding_map: Default::default(),
            zero_initialize_workgroup_memory: true,
        };
        let pipeline = glsl::PipelineOptions {
            shader_stage: stage,
            entry_point: entry.to_owned(),
            multiview: None,
        };
        let mut out = String::new();
        let reflection = glsl::Writer::new(
            &mut out,
            &one,
            &info,
            &options,
            &pipeline,
            naga::proc::BoundsCheckPolicies::default(),
        )
        .and_then(|mut w| w.write())
        .unwrap_or_else(|e| panic!("{label} {entry}: {e}"));
        assert!(
            reflection.immediates_items.is_empty() && reflection.clip_distance_count == 0,
            "{label} {entry}: no immediates or clip distances on WebGL 2"
        );
        if stage == naga::ShaderStage::Vertex {
            assert!(
                out.lines()
                    .any(|l| l.trim() == super::catalog::GLSL_ZERO_TO_ONE),
                "{label} {entry}: naga flips Y before each return"
            );
        }
        let binding = |var: naga::Handle<naga::GlobalVariable>| {
            let b = (one.global_variables[var].binding.as_ref()).expect("a bound global");
            format!("{} {}", b.group, b.binding)
        };
        let mut bindings: Vec<String> = (reflection.uniforms.iter())
            .map(|(&var, name)| format!("//@block {name} {}", binding(var)))
            .chain(reflection.texture_mapping.iter().map(|(name, m)| {
                let sampler = m.sampler.map(|s| format!(" {}", binding(s)));
                format!(
                    "//@texture {name} {}{}",
                    binding(m.texture),
                    sampler.unwrap_or_default()
                )
            }))
            .collect();
        bindings.sort();
        let version = out.find('\n').expect("a #version line") + 1;
        out.insert_str(version, &(bindings.join("\n") + "\n"));
        (out, constants)
    }

    /// Makes `module`'s overrides constants of the same names at their
    /// defaults, which naga writes as GLSL constants of those names; the
    /// constants' names.
    fn overrides_as_constants(module: &mut naga::Module) -> Vec<String> {
        let overrides = std::mem::take(&mut module.overrides);
        let mut names = Vec::new();
        let mut constants = std::collections::HashMap::new();
        for (handle, o) in overrides.iter() {
            let name = o.name.clone().expect("named overrides");
            let init = o.init.unwrap_or_else(|| panic!("`{name}` has a default"));
            let constant = naga::Constant {
                name: Some(name.clone()),
                ty: o.ty,
                init,
            };
            constants.insert(
                handle,
                module.constants.append(constant, Default::default()),
            );
            names.push(name);
        }
        let swap = |e: &mut naga::Expression| {
            if let naga::Expression::Override(o) = *e {
                *e = naga::Expression::Constant(constants[&o]);
            }
        };
        module
            .global_expressions
            .iter_mut()
            .for_each(|(_, e)| swap(e));
        let functions = (module.functions.iter_mut().map(|(_, f)| f))
            .chain(module.entry_points.iter_mut().map(|e| &mut e.function));
        for function in functions {
            function.expressions.iter_mut().for_each(|(_, e)| swap(e));
        }
        names
    }
}

/// What the build's `generated!` gives for a module this script writes,
/// before the module's name: the GLSL writer reads it back in its place.
const GENERATED: &str = "//generated ";

/// Splits each shader into one naga module per entry point and writes
/// `overrides.rs`, the override constants each entry point's module keeps:
/// a pipeline may set only those. With `ir`, also writes the modules,
/// postcard-encoded, deflated together to `OUT_DIR/ir.deflate`, and
/// `ir.rs`, which gives each module's bytes in the inflated whole by
/// label and entry point: a device that compiles with naga makes its
/// modules from these instead of parsing the WGSL again. The shaders share
/// most of their types and helpers, so together they deflate to an eighth.
fn entries(modules: &[(&str, naga::Module)], ir: bool) {
    let dir = std::env::var("OUT_DIR").expect("cargo sets OUT_DIR");
    let mut all = Vec::new();
    // Shaders that compose the same modules (variants that differ in
    // their entry points' names alone, or in nothing an entry point uses)
    // split into byte-identical modules: each is kept once.
    let mut kept: std::collections::HashMap<Vec<u8>, std::ops::Range<usize>> =
        std::collections::HashMap::new();
    let mut list =
        String::from("// Generated by build.rs.\npub(crate) const IR: &[(&str, Ranges)] = &[\n");
    let mut overrides =
        String::from("// Generated by build.rs.\npub(crate) const OVERRIDES: Overrides = &[\n");
    for (label, module) in modules {
        list.push_str(&format!("    ({label:?}, &[\n"));
        overrides.push_str(&format!("    ({label:?}, &[\n"));
        for (entry, one) in split::entry_modules(module) {
            let names: Vec<&str> = (one.overrides.iter())
                .filter_map(|(_, o)| o.name.as_deref())
                .collect();
            overrides.push_str(&format!("        ({entry:?}, &{names:?}),\n"));
            if ir {
                let bytes = postcard::to_allocvec(&one).expect("encodes a naga module");
                let at = kept.entry(bytes).or_insert_with_key(|bytes| {
                    let start = all.len();
                    all.extend_from_slice(bytes);
                    start..all.len()
                });
                list.push_str(&format!("        ({entry:?}, {}..{}),\n", at.start, at.end));
            }
        }
        list.push_str("    ]),\n");
        overrides.push_str("    ]),\n");
    }
    overrides.push_str("];\n");
    std::fs::write(format!("{dir}/overrides.rs"), overrides).expect("writes OUT_DIR/overrides.rs");
    if ir {
        list.push_str("];\n");
        let deflated = miniz_oxide::deflate::compress_to_vec(&all, 10);
        std::fs::write(format!("{dir}/ir.deflate"), deflated).expect("writes OUT_DIR/ir.deflate");
        std::fs::write(format!("{dir}/ir.rs"), list).expect("writes OUT_DIR/ir.rs");
    }
}

