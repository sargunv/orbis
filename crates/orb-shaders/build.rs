//! Reflects the scene tables' structs in `types.wgsl` and the shaders'
//! uniforms with naga: their layouts for Rust (`layout.rs`), so Rust never
//! mirrors them by hand. With the `ir` feature, also writes each shader's
//! naga modules (`ir.rs`).

fn main() {
    println!("cargo::rerun-if-changed=src/catalog.rs");
    println!("cargo::rerun-if-changed=src/split.rs");
    println!("cargo::rerun-if-changed=src/wgsl");
    reflect::write();
    strip();
    if std::env::var_os("CARGO_FEATURE_IR").is_some() {
        ir();
    }
}

/// Writes each shader's naga modules, one per entry point and
/// postcard-encoded, deflated together to `OUT_DIR/ir.deflate`, and
/// `ir.rs`, which gives each module's bytes in the inflated whole by
/// label and entry point: a device that compiles with naga makes its
/// modules from these instead of parsing the WGSL again. The shaders share
/// most of their types and helpers, so together they deflate to an eighth.
fn ir() {
    let dir = std::env::var("OUT_DIR").expect("cargo sets OUT_DIR");
    let mut all = Vec::new();
    let mut list =
        String::from("// Generated by build.rs.\npub(crate) const IR: &[(&str, Ranges)] = &[\n");
    for shader in catalog::SHADERS {
        let source = shader.source();
        let module = naga::front::wgsl::parse_str(&source)
            .unwrap_or_else(|e| panic!("{}: {}", shader.label, e.emit_to_string(&source)));
        list.push_str(&format!("    ({:?}, &[\n", shader.label));
        for (entry, one) in split::entry_modules(&module) {
            let start = all.len();
            all.extend(postcard::to_allocvec(&one).expect("encodes a naga module"));
            list.push_str(&format!("        ({entry:?}, {start}..{}),\n", all.len()));
        }
        list.push_str("    ]),\n");
    }
    list.push_str("];\n");
    let deflated = miniz_oxide::deflate::compress_to_vec(&all, 10);
    std::fs::write(format!("{dir}/ir.deflate"), deflated).expect("writes OUT_DIR/ir.deflate");
    std::fs::write(format!("{dir}/ir.rs"), list).expect("writes OUT_DIR/ir.rs");
}

