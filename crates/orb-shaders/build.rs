//! Reflects the scene tables' structs in `types.wgsl` with naga: their
//! layouts for Rust (`layout.rs`) and Compat's reassembly of rows from
//! data textures (`rows_compat.wgsl`), so neither side mirrors the other by
//! hand. With the `glsl` feature, also translates every Compat
//! composition to GLSL ES 3.00 (plan §8.4): one program per shader, with
//! the uniforms naga named for each WGSL binding.

fn main() {
    println!("cargo::rerun-if-changed=src/catalog.rs");
    println!("cargo::rerun-if-changed=src/wgsl");
    reflect::write();
    #[cfg(feature = "glsl")]
    glsl::write();
}

mod reflect {
    use std::fmt::Write;

    use naga::{Module, ScalarKind, TypeInner};

    /// The tables Rust writes and Compat reads row by row, and the
    /// function that reads one there (`None`: a uniform, read whole).
    const TABLES: &[(&str, &str, Option<&str>)] = &[
        ("Frame", "frame", None),
        ("Tile", "tile", Some("tile_word")),
        ("Chunk", "chunk", Some("chunk_word")),
        ("NodeCull", "node_cull", Some("node_cull_word")),
        ("Visible", "visible", Some("visible_word")),
    ];

    pub(crate) fn write() {
        let types = std::fs::read_to_string("src/wgsl/types.wgsl").expect("reads types.wgsl");
        // Its helpers read the frame block.
        let source = format!("{types}\n@group(0) @binding(0) var<uniform> frame: Frame;\n");
        let module = naga::front::wgsl::parse_str(&source)
            .unwrap_or_else(|e| panic!("types.wgsl: {}", e.emit_to_string(&source)));
        let mut layouter = naga::proc::Layouter::default();
        layouter
            .update(module.to_ctx())
            .expect("lays out types.wgsl");
        let mut rust = String::from("// Generated by build.rs from types.wgsl.\n");
        let mut wgsl = String::from("// Generated by orb-shaders' build.rs from types.wgsl.\n");
        for &(name, module_name, word) in TABLES {
            let (handle, ty) = module
                .types
                .iter()
                .find(|(_, t)| t.name.as_deref() == Some(name))
                .unwrap_or_else(|| panic!("types.wgsl has no {name}"));
            let TypeInner::Struct { members, span } = &ty.inner else {
                panic!("{name} is a struct");
            };
            writeln!(
                rust,
                "/// `types.wgsl`'s `{name}`: its words, and each member's first.\n\
                 pub mod {module_name} {{\n    pub const WORDS: usize = {};",
                span / 4
            )
            .unwrap();
            for m in members {
                let member = m.name.as_deref().expect("named members");
                writeln!(
                    rust,
                    "    pub const {}: usize = {};",
                    member.to_uppercase(),
                    m.offset / 4
                )
                .unwrap();
            }
            rust.push_str("}\n");
            let Some(word) = word else { continue };
            let _ = handle;
            writeln!(
                wgsl,
                "fn {module_name}_at(i: u32) -> {name} {{\n    let b = i * {}u;\n    var r: {name};",
                span / 4
            )
            .unwrap();
            for m in members {
                let member = m.name.as_deref().expect("named members");
                read(
                    &module,
                    m.ty,
                    &format!("r.{member}"),
                    m.offset / 4,
                    word,
                    &mut wgsl,
                );
            }
            wgsl.push_str("    return r;\n}\n");
        }
        let dir = std::env::var("OUT_DIR").expect("cargo sets OUT_DIR");
        std::fs::write(format!("{dir}/layout.rs"), rust).expect("writes OUT_DIR");
        std::fs::write(format!("{dir}/rows_compat.wgsl"), &wgsl).expect("writes OUT_DIR");
        ROWS.set(wgsl).expect("reflected once");
    }

    /// Compat's row reads, for the GLSL translation below.
    pub(crate) static ROWS: std::sync::OnceLock<String> = std::sync::OnceLock::new();

    /// Assigns `place` from the words at `at` on: scalars bitcast,
    /// vectors and arrays element by element.
    fn read(
        module: &Module,
        ty: naga::Handle<naga::Type>,
        place: &str,
        at: u32,
        word: &str,
        out: &mut String,
    ) {
        let scalar = |kind: ScalarKind| match kind {
            ScalarKind::Uint => "u32",
            ScalarKind::Sint => "i32",
            ScalarKind::Float => "f32",
            other => panic!("no {other:?} in a table"),
        };
        match &module.types[ty].inner {
            TypeInner::Scalar(s) => {
                writeln!(
                    out,
                    "    {place} = bitcast<{}>({word}(b + {at}u));",
                    scalar(s.kind)
                )
                .unwrap();
            }
            TypeInner::Vector { size, scalar: s } => {
                let n = *size as u32;
                let parts: Vec<String> = (0..n)
                    .map(|k| format!("bitcast<{}>({word}(b + {}u))", scalar(s.kind), at + k))
                    .collect();
                writeln!(
                    out,
                    "    {place} = vec{n}<{}>({});",
                    scalar(s.kind),
                    parts.join(", ")
                )
                .unwrap();
            }
            TypeInner::Array { base, size, stride } => {
                let naga::ArraySize::Constant(n) = size else {
                    panic!("fixed-size arrays in tables");
                };
                for k in 0..n.get() {
                    read(
                        module,
                        *base,
                        &format!("{place}[{k}]"),
                        at + k * stride / 4,
                        word,
                        out,
                    );
                }
            }
            other => panic!("no {other:?} in a table"),
        }
    }
}

#[cfg(feature = "glsl")]
#[allow(dead_code, unreachable_pub)]
#[path = "src/catalog.rs"]
mod catalog;

/// What `catalog.rs` composes Compat sources with.
#[cfg(feature = "glsl")]
fn rows_compat() -> &'static str {
    reflect::ROWS.get().expect("reflected first")
}

#[cfg(feature = "glsl")]
#[path = "src/translate.rs"]
mod translate;

#[cfg(feature = "glsl")]
mod glsl {
    use std::fmt::Write;

    use crate::catalog::COMPAT_SHADERS;

    pub(crate) fn write() {
        let mut out = String::from(
            "/// (shader label, program)\n\
             pub(crate) static PROGRAMS: &[(&str, orb_hal::GlslProgram<'static>)] = &[\n",
        );
        for shader in COMPAT_SHADERS {
            let source = shader.compat_source();
            let program =
                crate::translate::glsl(shader.label, &source, shader.vertex, shader.fragment, &[])
                    .unwrap_or_else(|e| panic!("{e}"));
            writeln!(
                out,
                "({:?}, orb_hal::GlslProgram {{ vertex: {:?}, fragment: {:?}, blocks: &{:?}, textures: &[{}] }}),",
                shader.label,
                program.vertex,
                program.fragment,
                program.blocks,
                program
                    .textures
                    .iter()
                    .map(|(name, texture, sampler)| format!(
                        "orb_hal::GlslTexture {{ name: {name:?}, texture: {texture:?}, sampler: {sampler:?} }}"
                    ))
                    .collect::<Vec<_>>()
                    .join(", "),
            )
            .expect("writes to a string");
        }
        out.push_str("];\n");
        let dir = std::env::var("OUT_DIR").expect("cargo sets OUT_DIR");
        std::fs::write(format!("{dir}/glsl.rs"), out).expect("writes OUT_DIR");
    }
}
