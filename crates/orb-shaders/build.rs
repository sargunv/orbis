/// Writes each WGSL module to `OUT_DIR/wgsl` without its comments,
/// indentation and blank lines, which the binaries would otherwise carry.
/// A `//planes ` line stays: [`Shader::source`](catalog::Shader::source)
/// turns it into code.
fn strip() {
    let out =
        std::path::Path::new(&std::env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("wgsl");
    std::fs::create_dir_all(&out).expect("creates OUT_DIR/wgsl");
    for entry in std::fs::read_dir("src/wgsl").expect("reads src/wgsl") {
        let path = entry.expect("lists src/wgsl").path();
        let source = std::fs::read_to_string(&path).expect("reads a WGSL module");
        let mut stripped = String::with_capacity(source.len());
        for line in source.lines() {
            let line = line.trim();
            let code = if line.starts_with("//planes ") {
                line
            } else {
                line.split_once("//")
                    .map_or(line, |(code, _)| code)
                    .trim_end()
            };
            if !code.is_empty() {
                stripped.push_str(code);
                stripped.push('\n');
            }
        }
        std::fs::write(out.join(path.file_name().expect("a file")), stripped)
            .expect("writes OUT_DIR/wgsl");
    }
}

mod reflect {
    use std::fmt::Write;

    use naga::TypeInner;

    /// The structs Rust writes that the shaders declare, by module name:
    /// each shader's uniforms and the types they hold.
    const STRUCTS: &[(&str, &str)] = &[
        ("FillNode", "fill_node"),
        ("LineNode", "line_node"),
        ("ExtrusionNode", "extrusion_node"),
        ("ElevationColor", "elevation_color"),
        ("CircleNode", "circle_node"),
        ("HeatmapNode", "heatmap_node"),
        ("RasterNode", "raster_node"),
        ("HillshadeNode", "hillshade_node"),
        ("ColorReliefNode", "color_relief_node"),
        ("SymbolNode", "symbol_node"),
        ("SymbolSize", "symbol_size"),
        ("Curve", "curve"),
        ("Pattern", "pattern"),
        ("StateLookup", "state_lookup"),
        ("Atmosphere", "atmosphere"),
        ("Terrain", "terrain"),
        ("TerrainTile", "terrain_tile"),
        ("Job", "prepare_job"),
        ("Candidate", "candidate"),
    ];

    /// The tables Rust writes, by module name.
    const TABLES: &[(&str, &str)] = &[
        ("Frame", "frame"),
        ("Tile", "tile"),
        ("Chunk", "chunk"),
        ("NodeCull", "node_cull"),
        ("Visible", "visible"),
    ];

    /// The rows WebGL 2's fetch modules read from data textures (#140):
    /// type, the reader's prefix (`{prefix}_at` from `{prefix}_word`) and
    /// the generated module it goes in.
    const ROWS: &[(&str, &str, &str)] = &[
        ("Tile", "tile", "rows_texture"),
        ("Chunk", "chunk", "rows_texture"),
        ("NodeCull", "node_cull", "rows_texture"),
        ("Visible", "visible", "rows_texture"),
        ("ImageRect", "image", "rows_texture"),
        ("TerrainTile", "terrain_tile", "terrain_rows_texture"),
    ];

    pub(crate) fn write(modules: &[(&str, naga::Module)]) {
        let types = std::fs::read_to_string("src/wgsl/types.wgsl").expect("reads types.wgsl");
        // Its helpers read the frame block.
        let source = format!("{types}\n@group(0) @binding(0) var<uniform> frame: Frame;\n");
        let module = naga::front::wgsl::parse_str(&source)
            .unwrap_or_else(|e| panic!("types.wgsl: {}", e.emit_to_string(&source)));
        let mut layouter = naga::proc::Layouter::default();
        layouter
            .update(module.to_ctx())
            .expect("lays out types.wgsl");
        let mut rust = String::from("// Generated by build.rs from types.wgsl.\n");
        // Its counts and offsets: the property rows' words and the `MAX_`
        // limits.
        for (_, c) in module.constants.iter() {
            let name = c.name.as_deref().unwrap_or_default();
            if let (true, naga::Expression::Literal(naga::Literal::U32(v))) = (
                name.contains("_ROW_") || name.starts_with("MAX_"),
                &module.global_expressions[c.init],
            ) {
                writeln!(rust, "pub const {name}: usize = {v};").unwrap();
            }
        }
        for &(name, module_name) in TABLES {
            let (_, ty) = module
                .types
                .iter()
                .find(|(_, t)| t.name.as_deref() == Some(name))
                .unwrap_or_else(|| panic!("types.wgsl has no {name}"));
            emit_struct(&mut rust, "types.wgsl", (name, module_name), &ty.inner);
        }
        let mut done = std::collections::HashSet::new();
        let mut rows: std::collections::BTreeMap<&str, String> = Default::default();
        for (label, module) in modules {
            let mut layouter = naga::proc::Layouter::default();
            layouter
                .update(module.to_ctx())
                .expect("lays out the shader");
            for (_, ty) in module.types.iter() {
                let Some(&(name, prefix, file)) =
                    ROWS.iter().find(|(n, _, _)| ty.name.as_deref() == Some(n))
                else {
                    continue;
                };
                let TypeInner::Struct { members, span } = &ty.inner else {
                    continue;
                };
                if !done.insert(prefix) {
                    continue;
                }
                let out = rows.entry(file).or_default();
                writeln!(
                    out,
                    "fn {prefix}_at(i: u32) -> {name} {{\nlet b = i * {}u;\nvar r: {name};",
                    span / 4
                )
                .unwrap();
                for m in members {
                    let member = m.name.as_deref().expect("named members");
                    let place = format!("r.{member}");
                    let word = format!("{prefix}_word");
                    read(module, m.ty, &place, m.offset / 4, &word, out);
                }
                out.push_str("return r;\n}\n");
            }
            for (_, ty) in module.types.iter() {
                let Some(&(name, module_name)) =
                    STRUCTS.iter().find(|(n, _)| ty.name.as_deref() == Some(n))
                else {
                    continue;
                };
                if matches!(ty.inner, TypeInner::Struct { .. }) && done.insert(name) {
                    emit_struct(&mut rust, label, (name, module_name), &ty.inner);
                }
            }
        }
        if let Some(missing) = STRUCTS.iter().find(|(n, _)| !done.contains(n)) {
            panic!("no shader declares {}", missing.0);
        }
        if let Some(missing) = ROWS.iter().find(|(_, p, _)| !done.contains(p)) {
            panic!("no shader declares {}", missing.0);
        }
        let dir = std::env::var("OUT_DIR").expect("cargo sets OUT_DIR");
        std::fs::write(format!("{dir}/layout.rs"), rust).expect("writes OUT_DIR");
        std::fs::create_dir_all(format!("{dir}/wgsl")).expect("creates OUT_DIR/wgsl");
        for (file, text) in rows {
            std::fs::write(format!("{dir}/wgsl/{file}.wgsl"), text).expect("writes OUT_DIR");
        }
    }

    /// Writes struct `name`'s words and each member's first word as Rust
    /// module `module_name`'s constants.
    fn emit_struct(
        rust: &mut String,
        from: &str,
        (name, module_name): (&str, &str),
        ty: &TypeInner,
    ) {
        let TypeInner::Struct { members, span } = ty else {
            panic!("{name} is a struct");
        };
        writeln!(
            rust,
            "/// `{from}`'s `{name}`: its words, and each member's first.\n\
             pub mod {module_name} {{\n    pub const WORDS: usize = {};",
            span / 4
        )
        .unwrap();
        for m in members {
            let member = m.name.as_deref().expect("named members");
            let offset = m.offset / 4;
            writeln!(
                rust,
                "    pub const {}: usize = {offset};",
                member.to_uppercase()
            )
            .unwrap();
        }
        rust.push_str("}\n");
    }

    /// Assigns `place` from the words at `at` on: scalars bitcast,
    /// vectors and arrays element by element.
    fn read(
        module: &naga::Module,
        ty: naga::Handle<naga::Type>,
        place: &str,
        at: u32,
        word: &str,
        out: &mut String,
    ) {
        let scalar = |kind: naga::ScalarKind| match kind {
            naga::ScalarKind::Uint => "u32",
            naga::ScalarKind::Sint => "i32",
            naga::ScalarKind::Float => "f32",
            other => panic!("no {other:?} in a table"),
        };
        match &module.types[ty].inner {
            TypeInner::Scalar(s) => {
                let ty = scalar(s.kind);
                writeln!(out, "{place} = bitcast<{ty}>({word}(b + {at}u));").unwrap();
            }
            TypeInner::Vector { size, scalar: s } => {
                let (n, ty) = (*size as u32, scalar(s.kind));
                let parts: Vec<String> = (0..n)
                    .map(|k| format!("bitcast<{ty}>({word}(b + {}u))", at + k))
                    .collect();
                writeln!(out, "{place} = vec{n}<{ty}>({});", parts.join(", ")).unwrap();
            }
            TypeInner::Array { base, size, stride } => {
                let naga::ArraySize::Constant(n) = size else {
                    panic!("fixed-size arrays in tables");
                };
                for k in 0..n.get() {
                    let place = format!("{place}[{k}]");
                    read(module, *base, &place, at + k * stride / 4, word, out);
                }
            }
            other => panic!("no {other:?} in a table"),
        }
    }
}

/// The build script reflects the source tree's modules.
macro_rules! wgsl {
    ($name:literal) => {
        include_str!(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/src/wgsl/",
            $name,
            ".wgsl"
        ))
    };
}

/// Modules this script writes, which it doesn't read back.
macro_rules! generated {
    ($name:literal) => {
        ""
    };
}

