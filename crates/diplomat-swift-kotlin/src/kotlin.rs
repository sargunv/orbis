//! Kotlin over JNI: a Kotlin file per type, an internal object with the
//! `external` functions and the factories the shim calls back, and a C
//! shim that marshals each call to Diplomat's C function.
//!
//! Marshalling: scalars pass as JNI scalars (unsigned as their signed
//! twins), enums as their discriminant, structs flattened into their
//! scalar leaves in and built by a factory out, opaque objects as their
//! address, strings as UTF-8 byte arrays, slices as primitive arrays, text
//! out as a byte array decoded in Kotlin, callbacks as global references.

use std::fmt::Write;

use crate::model::{Api, Def, Fail, Kind, Method, Param, Prim, Ret, Thread, Ty};
use crate::names::{comment, jni_mangle, lower_camel, lower_first};
use crate::{Files, KotlinConfig};

const HEADER: &str = "// Generated by diplomat-swift-kotlin. Do not edit.\n";

pub(crate) fn emit(api: &Api, config: &KotlinConfig) -> Result<Files, Vec<String>> {
    let k = Kotlin { api, config };
    let dir = format!("kotlin/{}", config.package.replace('.', "/"));
    let mut files = Files::new();
    for def in &api.defs {
        files.insert(format!("{dir}/{}.kt", def.name), k.def(def));
    }
    for error in api.errors() {
        files.insert(format!("{dir}/{error}Exception.kt"), k.exception(error));
    }
    files.insert(
        format!("{dir}/{}.kt", config.native_object),
        k.native_object(),
    );
    files.insert(format!("jni/{}_jni.c", config.library), k.shim());
    Ok(files)
}

struct Kotlin<'a> {
    api: &'a Api,
    config: &'a KotlinConfig,
}

/// The JNI scalar types.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum JniPrim {
    Boolean,
    Byte,
    Short,
    Int,
    Long,
    Float,
    Double,
}

impl JniPrim {
    fn of(p: Prim) -> Self {
        match p {
            Prim::Bool => Self::Boolean,
            Prim::I8 | Prim::U8 => Self::Byte,
            Prim::I16 | Prim::U16 => Self::Short,
            Prim::I32 | Prim::U32 => Self::Int,
            Prim::I64 | Prim::U64 | Prim::Isize | Prim::Usize => Self::Long,
            Prim::F32 => Self::Float,
            Prim::F64 => Self::Double,
        }
    }

    fn kotlin(self) -> &'static str {
        match self {
            Self::Boolean => "Boolean",
            Self::Byte => "Byte",
            Self::Short => "Short",
            Self::Int => "Int",
            Self::Long => "Long",
            Self::Float => "Float",
            Self::Double => "Double",
        }
    }

    fn c(self) -> &'static str {
        match self {
            Self::Boolean => "jboolean",
            Self::Byte => "jbyte",
            Self::Short => "jshort",
            Self::Int => "jint",
            Self::Long => "jlong",
            Self::Float => "jfloat",
            Self::Double => "jdouble",
        }
    }

    fn signature(self) -> char {
        match self {
            Self::Boolean => 'Z',
            Self::Byte => 'B',
            Self::Short => 'S',
            Self::Int => 'I',
            Self::Long => 'J',
            Self::Float => 'F',
            Self::Double => 'D',
        }
    }

    /// The array type and its JNI accessors' infix (`Byte` in
    /// `GetByteArrayElements`).
    fn array(self) -> (&'static str, &'static str, &'static str) {
        match self {
            Self::Boolean => ("BooleanArray", "jbooleanArray", "Boolean"),
            Self::Byte => ("ByteArray", "jbyteArray", "Byte"),
            Self::Short => ("ShortArray", "jshortArray", "Short"),
            Self::Int => ("IntArray", "jintArray", "Int"),
            Self::Long => ("LongArray", "jlongArray", "Long"),
            Self::Float => ("FloatArray", "jfloatArray", "Float"),
            Self::Double => ("DoubleArray", "jdoubleArray", "Double"),
        }
    }
}

/// The public Kotlin type of a scalar.
fn kotlin_prim(p: Prim) -> &'static str {
    match p {
        Prim::Bool => "Boolean",
        Prim::I8 => "Byte",
        Prim::U8 => "UByte",
        Prim::I16 => "Short",
        Prim::U16 => "UShort",
        Prim::I32 => "Int",
        Prim::U32 => "UInt",
        Prim::I64 | Prim::Isize => "Long",
        Prim::U64 | Prim::Usize => "ULong",
        Prim::F32 => "Float",
        Prim::F64 => "Double",
    }
}

/// Public value to its JNI twin.
fn to_jni(p: Prim, expr: &str) -> String {
    match p {
        Prim::U8 => format!("{expr}.toByte()"),
        Prim::U16 => format!("{expr}.toShort()"),
        Prim::U32 => format!("{expr}.toInt()"),
        Prim::U64 | Prim::Usize => format!("{expr}.toLong()"),
        _ => expr.to_owned(),
    }
}

/// JNI value to its public twin.
fn from_jni(p: Prim, expr: &str) -> String {
    match p {
        Prim::U8 => format!("{expr}.toUByte()"),
        Prim::U16 => format!("{expr}.toUShort()"),
        Prim::U32 => format!("{expr}.toUInt()"),
        Prim::U64 | Prim::Usize => format!("{expr}.toULong()"),
        _ => expr.to_owned(),
    }
}

/// C scalar to JNI scalar.
fn c_to_jni(p: Prim, expr: &str) -> String {
    match p {
        Prim::Bool => format!("({expr}) ? JNI_TRUE : JNI_FALSE"),
        _ => format!("({})({expr})", JniPrim::of(p).c()),
    }
}

const KEYWORDS: &[&str] = &[
    "as",
    "break",
    "class",
    "continue",
    "do",
    "else",
    "false",
    "for",
    "fun",
    "if",
    "in",
    "interface",
    "is",
    "null",
    "object",
    "package",
    "return",
    "super",
    "this",
    "throw",
    "true",
    "try",
    "typealias",
    "typeof",
    "val",
    "var",
    "when",
    "while",
];

fn ident(name: &str) -> String {
    let name = lower_camel(name);
    if KEYWORDS.contains(&name.as_str()) {
        format!("`{name}`")
    } else {
        name
    }
}

impl Kotlin<'_> {
    fn native(&self) -> &str {
        &self.config.native_object
    }

    fn class_path(&self, name: &str) -> String {
        format!("{}/{name}", self.config.package.replace('.', "/"))
    }

    /// The external function's name for a C function.
    fn external(&self, abi: &str) -> String {
        lower_first(&lower_camel(&abi.replace("__", "_")))
    }

    /// Scalar leaves of a struct or enum value, depth first.
    fn leaves(&self, path: Vec<String>, ty: &Ty) -> Vec<(Vec<String>, Ty)> {
        match ty {
            Ty::Struct(name) => self
                .api
                .fields(name)
                .iter()
                .flat_map(|f| {
                    let mut p = path.clone();
                    p.push(f.name.clone());
                    self.leaves(p, &f.ty)
                })
                .collect(),
            _ => vec![(path, ty.clone())],
        }
    }

    fn leaf_prim(ty: &Ty) -> JniPrim {
        match ty {
            Ty::Prim(p) => JniPrim::of(*p),
            Ty::Enum(_) => JniPrim::Int,
            _ => unreachable!("struct leaves are scalars and enums"),
        }
    }

    fn public_type(&self, ty: &Ty) -> String {
        match ty {
            Ty::Prim(p) => kotlin_prim(*p).into(),
            Ty::Enum(n) | Ty::Struct(n) => n.clone(),
            Ty::Opaque { name, optional, .. } => {
                format!("{name}{}", if *optional { "?" } else { "" })
            }
            Ty::Str => "String".into(),
            Ty::Slice(p) => JniPrim::of(*p).array().0.into(),
            Ty::Callback => "() -> Unit".into(),
        }
    }

    fn def(&self, def: &Def) -> String {
        let mut out = format!("{HEADER}package {}\n\n", self.config.package);
        match &def.kind {
            Kind::Enum { variants } => {
                out += &comment(&def.docs, " * ", "").pipe_doc("");
                writeln!(out, "enum class {}(val value: Int) {{", def.name).unwrap();
                for (i, (name, value, docs)) in variants.iter().enumerate() {
                    out += &comment(docs, " * ", "    ").pipe_doc("    ");
                    let end = if i + 1 == variants.len() { ";" } else { "," };
                    writeln!(out, "    {name}({value}){end}").unwrap();
                }
                out += "\n    companion object {\n";
                writeln!(
                    out,
                    "        @JvmStatic\n        fun fromValue(value: Int): {0} =\n            values().firstOrNull {{ it.value == value }}\n                ?: throw IllegalArgumentException(\"no {0} has the value $value\")",
                    def.name
                )
                .unwrap();
                for m in &def.methods {
                    out += &self.method(m, "        ");
                }
                out += "    }\n}\n";
            }
            Kind::Struct { fields } => {
                out += &comment(&def.docs, " * ", "").pipe_doc("");
                writeln!(out, "data class {}(", def.name).unwrap();
                for f in fields {
                    out += &comment(&f.docs, " * ", "    ").pipe_doc("    ");
                    writeln!(
                        out,
                        "    val {}: {},",
                        ident(&f.name),
                        self.public_type(&f.ty)
                    )
                    .unwrap();
                }
                out += ")";
                if def.methods.is_empty() {
                    out += "\n";
                } else {
                    out += " {\n    companion object {\n";
                    for m in &def.methods {
                        out += &self.method(m, "        ");
                    }
                    out += "    }\n}\n";
                }
            }
            Kind::Opaque { destroy, thread } => {
                let mut docs = def.docs.clone();
                if *thread == Thread::Owner {
                    docs += "\n\nUse it only on the thread that created it.";
                } else {
                    docs += "\n\nIt may be used on any thread.";
                }
                docs += " Release it with [close]; owned objects that are never closed leak.";
                out += &comment(docs.trim_start(), " * ", "").pipe_doc("");
                writeln!(
                    out,
                    "class {} internal constructor(handle: Long) : AutoCloseable {{",
                    def.name
                )
                .unwrap();
                out +=
                    "    @Volatile\n    internal var handle: Long = handle\n        private set\n";
                if *thread == Thread::Owner {
                    out += "    private val owner: Thread = Thread.currentThread()\n";
                }
                out += "\n    internal fun live(): Long {\n";
                if *thread == Thread::Owner {
                    writeln!(
                        out,
                        "        check(Thread.currentThread() === owner) {{\n            \"{} belongs to thread ${{owner.name}}, not ${{Thread.currentThread().name}}\"\n        }}",
                        def.name
                    )
                    .unwrap();
                }
                writeln!(
                    out,
                    "        val h = handle\n        check(h != 0L) {{ \"{} is closed\" }}\n        return h\n    }}\n",
                    def.name
                )
                .unwrap();
                let destroy_fn = self.external(destroy);
                if *thread == Thread::Owner {
                    writeln!(
                        out,
                        "    override fun close() {{\n        if (handle != 0L) {{\n            val h = live()\n            handle = 0L\n            {}.{destroy_fn}(h)\n        }}\n    }}\n",
                        self.native()
                    )
                    .unwrap();
                } else {
                    writeln!(
                        out,
                        "    override fun close() {{\n        val h = synchronized(this) {{\n            val h = handle\n            handle = 0L\n            h\n        }}\n        if (h != 0L) {}.{destroy_fn}(h)\n    }}\n",
                        self.native()
                    )
                    .unwrap();
                }
                let (statics, instance): (Vec<_>, Vec<_>) =
                    def.methods.iter().partition(|m| m.receiver.is_none());
                for m in instance {
                    out += &self.method(m, "    ");
                }
                if !statics.is_empty() {
                    out += "    companion object {\n";
                    for m in statics {
                        out += &self.method(m, "        ");
                    }
                    out += "    }\n";
                }
                out += "}\n";
            }
        }
        out
    }

    fn method_docs(&self, m: &Method) -> String {
        let mut docs = m.docs.clone();
        if let Some(category) = &m.category {
            if !docs.is_empty() {
                docs += "\n\n";
            }
            write!(docs, "Contract: `{category}`.").unwrap();
        }
        if let Fail::Enum(e) = &m.fail {
            write!(docs, "\n\n@throws {e}Exception when it fails.").unwrap();
        }
        docs
    }

    /// A Kotlin method calling its external function.
    fn method(&self, m: &Method, indent: &str) -> String {
        let mut out = comment(&self.method_docs(m), " * ", indent).pipe_doc(indent);
        let params: Vec<String> = m
            .params
            .iter()
            .map(|p| format!("{}: {}", ident(&p.name), self.public_type(&p.ty)))
            .collect();
        let ret = match &m.ret {
            Ret::Unit => String::new(),
            Ret::Write => ": String".into(),
            Ret::Value(ty) => format!(": {}", self.public_type(ty)),
        };
        if m.receiver.is_none() {
            writeln!(out, "{indent}@JvmStatic").unwrap();
        }
        writeln!(
            out,
            "{indent}fun {}({}){ret} {{",
            ident(&m.name),
            params.join(", ")
        )
        .unwrap();
        let mut args = Vec::new();
        if m.receiver.is_some() {
            args.push("live()".to_owned());
        }
        for p in &m.params {
            args.extend(self.kotlin_args(p));
        }
        let call = format!(
            "{}.{}({})",
            self.native(),
            self.external(&m.abi),
            args.join(", ")
        );
        let body = match &m.ret {
            Ret::Unit => call,
            Ret::Write => format!("return {call}.decodeToString()"),
            Ret::Value(ty) => format!("return {}", self.kotlin_result(ty, &call)),
        };
        writeln!(out, "{indent}    {body}\n{indent}}}\n").unwrap();
        out
    }

    /// The JNI arguments for a parameter.
    fn kotlin_args(&self, p: &Param) -> Vec<String> {
        let name = ident(&p.name);
        match &p.ty {
            Ty::Prim(prim) => vec![to_jni(*prim, &name)],
            Ty::Enum(_) => vec![format!("{name}.value")],
            Ty::Struct(_) => self
                .leaves(vec![name.clone()], &p.ty)
                .into_iter()
                .map(|(path, ty)| {
                    let expr = path
                        .iter()
                        .enumerate()
                        .map(|(i, s)| if i == 0 { s.clone() } else { ident(s) })
                        .collect::<Vec<_>>()
                        .join(".");
                    match ty {
                        Ty::Prim(prim) => to_jni(prim, &expr),
                        Ty::Enum(_) => format!("{expr}.value"),
                        _ => unreachable!(),
                    }
                })
                .collect(),
            Ty::Opaque { optional, .. } => vec![if *optional {
                format!("{name}?.live() ?: 0L")
            } else {
                format!("{name}.live()")
            }],
            Ty::Str => vec![format!("{name}.encodeToByteArray()")],
            Ty::Slice(_) | Ty::Callback => vec![name],
        }
    }

    fn kotlin_result(&self, ty: &Ty, call: &str) -> String {
        match ty {
            Ty::Prim(p) => from_jni(*p, call),
            Ty::Enum(e) => format!("{e}.fromValue({call})"),
            Ty::Struct(_) | Ty::Slice(_) => call.to_owned(),
            Ty::Opaque {
                name,
                optional: true,
                ..
            } => format!("{call}.let {{ if (it == 0L) null else {name}(it) }}"),
            Ty::Opaque { name, .. } => format!("{name}({call})"),
            Ty::Str | Ty::Callback => unreachable!("not a return type"),
        }
    }

    fn exception(&self, error: &str) -> String {
        format!(
            "{HEADER}package {}\n\n/** A call failed with [{error}] [error]. */\nclass {error}Exception(val error: {error}, message: String) : RuntimeException(message)\n",
            self.config.package
        )
    }

    /// JNI parameter types of a method's external function.
    fn jni_params(&self, m: &Method) -> Vec<(String, String, String)> {
        // (Kotlin name: type, C type, C name)
        let mut out = Vec::new();
        if m.receiver.is_some() {
            out.push(("self".into(), "Long".into(), "jlong".into()));
        }
        for p in &m.params {
            let name = lower_camel(&p.name);
            match &p.ty {
                Ty::Prim(prim) => {
                    let j = JniPrim::of(*prim);
                    out.push((name, j.kotlin().into(), j.c().into()));
                }
                Ty::Enum(_) => out.push((name, "Int".into(), "jint".into())),
                Ty::Struct(_) => {
                    for (path, ty) in self.leaves(vec![name.clone()], &p.ty) {
                        let j = Self::leaf_prim(&ty);
                        out.push((path.join("_"), j.kotlin().into(), j.c().into()));
                    }
                }
                Ty::Opaque { .. } => out.push((name, "Long".into(), "jlong".into())),
                Ty::Str => out.push((name, "ByteArray".into(), "jbyteArray".into())),
                Ty::Slice(prim) => {
                    let (k, c, _) = JniPrim::of(*prim).array();
                    out.push((name, k.into(), c.into()));
                }
                Ty::Callback => {
                    out.push((name, "Function0<Unit>".into(), "jobject".into()));
                }
            }
        }
        out
    }

    /// The external function's Kotlin and C return types.
    fn jni_return(&self, m: &Method) -> (String, &'static str) {
        match &m.ret {
            Ret::Unit => ("Unit".into(), "void"),
            Ret::Write => ("ByteArray".into(), "jbyteArray"),
            Ret::Value(ty) => match ty {
                Ty::Prim(p) => (JniPrim::of(*p).kotlin().into(), JniPrim::of(*p).c()),
                Ty::Enum(_) => ("Int".into(), "jint"),
                Ty::Struct(n) => (n.clone(), "jobject"),
                Ty::Opaque { .. } => ("Long".into(), "jlong"),
                Ty::Slice(p) => (JniPrim::of(*p).array().0.into(), JniPrim::of(*p).array().1),
                Ty::Str | Ty::Callback => unreachable!("not a return type"),
            },
        }
    }

    fn all_methods(&self) -> impl Iterator<Item = (&Def, &Method)> {
        self.api
            .defs
            .iter()
            .flat_map(|d| d.methods.iter().map(move |m| (d, m)))
    }

    fn native_object(&self) -> String {
        let mut out = format!(
            "{HEADER}package {}\n\n/** The JNI functions, and the factories the shim calls back. */\n@Suppress(\"FunctionName\", \"unused\")\ninternal object {} {{\n    init {{\n        System.loadLibrary(\"{}\")\n    }}\n\n",
            self.config.package,
            self.native(),
            self.config.library
        );
        for def in &self.api.defs {
            if let Kind::Opaque { destroy, .. } = &def.kind {
                writeln!(
                    out,
                    "    @JvmStatic\n    external fun {}(self: Long)\n",
                    self.external(destroy)
                )
                .unwrap();
            }
        }
        for (_, m) in self.all_methods() {
            let params: Vec<String> = self
                .jni_params(m)
                .into_iter()
                .map(|(n, t, _)| format!("{n}: {t}"))
                .collect();
            let (ret, _) = self.jni_return(m);
            writeln!(
                out,
                "    @JvmStatic\n    external fun {}({}): {ret}\n",
                self.external(&m.abi),
                params.join(", ")
            )
            .unwrap();
        }
        // Factories for structs returned by value.
        for def in &self.api.defs {
            if let Kind::Struct { .. } = &def.kind {
                let leaves = self.leaves(vec![], &Ty::Struct(def.name.clone()));
                let params: Vec<String> = leaves
                    .iter()
                    .map(|(path, ty)| {
                        format!("{}: {}", path.join("_"), Self::leaf_prim(ty).kotlin())
                    })
                    .collect();
                writeln!(
                    out,
                    "    @JvmStatic\n    fun new{0}({1}): {0} = {2}\n",
                    def.name,
                    params.join(", "),
                    self.build_struct(&def.name, &[])
                )
                .unwrap();
            }
        }
        for error in self.api.errors() {
            writeln!(
                out,
                "    @JvmStatic\n    fun new{error}Exception(value: Int, message: ByteArray): Throwable =\n        {error}Exception({error}.fromValue(value), message.decodeToString())\n"
            )
            .unwrap();
        }
        out += "}\n";
        out
    }

    /// A Kotlin expression building a struct from the factory's leaf
    /// parameters under `prefix`.
    fn build_struct(&self, name: &str, prefix: &[String]) -> String {
        let args: Vec<String> = self
            .api
            .fields(name)
            .iter()
            .map(|f| {
                let mut path = prefix.to_vec();
                path.push(f.name.clone());
                let leaf = path.join("_");
                match &f.ty {
                    Ty::Prim(p) => from_jni(*p, &leaf),
                    Ty::Enum(e) => format!("{e}.fromValue({leaf})"),
                    Ty::Struct(s) => self.build_struct(s, &path),
                    _ => unreachable!(),
                }
            })
            .collect();
        format!("{name}({})", args.join(", "))
    }

    fn shim(&self) -> String {
        let native_class = self.class_path(self.native());
        let jni_prefix = format!("Java_{}_", jni_mangle(&native_class));
        let mut out = String::from(
            "// Generated by diplomat-swift-kotlin. Do not edit.\n// The JNI side of the Kotlin bindings: each function marshals its\n// arguments and calls Diplomat's C function.\n\n#include <jni.h>\n#include <stdbool.h>\n#include <stdint.h>\n#include <stddef.h>\n\n",
        );
        for header in &self.config.c_headers {
            writeln!(out, "#include \"{header}\"").unwrap();
        }
        let params = || self.all_methods().flat_map(|(_, m)| m.params.iter());
        let callbacks = params().any(|p| p.ty == Ty::Callback);
        let writes = self.all_methods().any(|(_, m)| m.ret == Ret::Write)
            || self.api.error_messages.values().any(Option::is_some);
        let unit_failures = self.all_methods().any(|(_, m)| m.fail == Fail::Unit);
        out += "\nstatic JavaVM* g_vm;\nstatic jclass g_native;\n";
        if callbacks {
            out += "static jmethodID g_function0_invoke;\n";
        }
        let structs: Vec<&Def> = self
            .api
            .defs
            .iter()
            .filter(|d| matches!(d.kind, Kind::Struct { .. }))
            .collect();
        for s in &structs {
            writeln!(out, "static jmethodID g_new_{};", s.name).unwrap();
        }
        for e in self.api.errors() {
            writeln!(out, "static jmethodID g_new_{e}_exception;").unwrap();
        }
        if callbacks {
            out += r#"
/* The calling thread's JNIEnv, attaching threads the JVM doesn't know. */
static JNIEnv* attached_env(void) {
    JNIEnv* env = NULL;
    if ((*g_vm)->GetEnv(g_vm, (void**)&env, JNI_VERSION_1_6) == JNI_EDETACHED) {
#ifdef __ANDROID__
        (*g_vm)->AttachCurrentThreadAsDaemon(g_vm, &env, NULL);
#else
        (*g_vm)->AttachCurrentThreadAsDaemon(g_vm, (void**)&env, NULL);
#endif
    }
    return env;
}

static void callback_run(const void* data) {
    JNIEnv* env = attached_env();
    jobject result = (*env)->CallObjectMethod(env, (jobject)data, g_function0_invoke);
    if ((*env)->ExceptionCheck(env)) {
        (*env)->ExceptionDescribe(env);
        (*env)->ExceptionClear(env);
    }
    if (result) (*env)->DeleteLocalRef(env, result);
}

static void callback_destroy(const void* data) {
    JNIEnv* env = attached_env();
    (*env)->DeleteGlobalRef(env, (jobject)data);
}
"#;
        }
        if writes {
            out += r#"
static jbyteArray write_to_bytes(JNIEnv* env, DiplomatWrite* write) {
    jsize len = (jsize)diplomat_buffer_write_len(write);
    jbyteArray bytes = (*env)->NewByteArray(env, len);
    if (bytes) {
        (*env)->SetByteArrayRegion(env, bytes, 0, len,
                                   (const jbyte*)diplomat_buffer_write_get_bytes(write));
    }
    diplomat_buffer_write_destroy(write);
    return bytes;
}
"#;
        }
        let mut slices: Vec<Prim> = Vec::new();
        for (_, m) in self.all_methods() {
            if let Ret::Value(Ty::Slice(p)) = &m.ret
                && !slices.contains(p)
            {
                slices.push(*p);
            }
        }
        for p in slices {
            let j = JniPrim::of(p);
            let (_, array, infix) = j.array();
            write!(
                out,
                "\nstatic {array} new_{d}_array(JNIEnv* env, const {c}* data, size_t len) {{\n    {array} array = (*env)->New{infix}Array(env, (jsize)len);\n    if (!array || len == 0) return array;\n    {jc}* items = (*env)->Get{infix}ArrayElements(env, array, NULL);\n    if (!items) return array;\n    for (size_t i = 0; i < len; i++) items[i] = ({jc})data[i];\n    (*env)->Release{infix}ArrayElements(env, array, items, 0);\n    return array;\n}}\n",
                d = p.derived(),
                c = p.c(),
                jc = j.c()
            )
            .unwrap();
        }
        for e in self.api.errors() {
            let message = match &self.api.error_messages[e] {
                Some(m) => {
                    let abi = &self
                        .api
                        .def(e)
                        .methods
                        .iter()
                        .find(|x| &x.name == m)
                        .expect("checked in lowering")
                        .abi;
                    format!(
                        "    DiplomatWrite* write = diplomat_buffer_write_create(0);\n    {abi}(write);\n    jbyteArray message = write_to_bytes(env, write);\n"
                    )
                }
                None => "    jbyteArray message = (*env)->NewByteArray(env, 0);\n".into(),
            };
            write!(
                out,
                "\nstatic void throw_{e}(JNIEnv* env, {e} error) {{\n{message}    jobject exception = (*env)->CallStaticObjectMethod(env, g_native, g_new_{e}_exception, (jint)error, message);\n    if (exception) (*env)->Throw(env, (jthrowable)exception);\n}}\n"
            )
            .unwrap();
        }
        if unit_failures {
            out += "\nstatic void throw_unit(JNIEnv* env, const char* what) {\n    jclass type = (*env)->FindClass(env, \"java/lang/RuntimeException\");\n    if (type) (*env)->ThrowNew(env, type, what);\n}\n";
        }

        // JNI_OnLoad: cache the classes and methods.
        write!(
            out,
            "\nJNIEXPORT jint JNICALL JNI_OnLoad(JavaVM* vm, void* reserved) {{\n    (void)reserved;\n    g_vm = vm;\n    JNIEnv* env;\n    if ((*vm)->GetEnv(vm, (void**)&env, JNI_VERSION_1_6) != JNI_OK) return JNI_ERR;\n    jclass native = (*env)->FindClass(env, \"{native_class}\");\n    if (!native) return JNI_ERR;\n    g_native = (jclass)(*env)->NewGlobalRef(env, native);\n"
        )
        .unwrap();
        if callbacks {
            out += "    jclass function0 = (*env)->FindClass(env, \"kotlin/jvm/functions/Function0\");\n    if (!function0) return JNI_ERR;\n    g_function0_invoke = (*env)->GetMethodID(env, function0, \"invoke\", \"()Ljava/lang/Object;\");\n";
        }
        for s in &structs {
            let sig: String = self
                .leaves(vec![], &Ty::Struct(s.name.clone()))
                .iter()
                .map(|(_, ty)| Self::leaf_prim(ty).signature())
                .collect();
            writeln!(
                out,
                "    g_new_{0} = (*env)->GetStaticMethodID(env, g_native, \"new{0}\", \"({sig})L{1};\");",
                s.name,
                self.class_path(&s.name)
            )
            .unwrap();
        }
        for e in self.api.errors() {
            writeln!(
                out,
                "    g_new_{e}_exception = (*env)->GetStaticMethodID(env, g_native, \"new{e}Exception\", \"(I[B)Ljava/lang/Throwable;\");"
            )
            .unwrap();
        }
        out += "    if ((*env)->ExceptionCheck(env)) return JNI_ERR;\n    return JNI_VERSION_1_6;\n}\n";

        for def in &self.api.defs {
            if let Kind::Opaque { destroy, .. } = &def.kind {
                write!(
                    out,
                    "\nJNIEXPORT void JNICALL {jni_prefix}{}(JNIEnv* env, jclass cls, jlong self) {{\n    (void)env;\n    (void)cls;\n    {destroy}(({}*)(intptr_t)self);\n}}\n",
                    jni_mangle(&self.external(destroy)),
                    def.name
                )
                .unwrap();
            }
        }
        for (def, m) in self.all_methods() {
            out += &self.shim_method(def, m, &jni_prefix);
        }
        out
    }

    fn shim_method(&self, def: &Def, m: &Method, jni_prefix: &str) -> String {
        let (_, c_ret) = self.jni_return(m);
        let mut params = vec!["JNIEnv* env".to_owned(), "jclass cls".to_owned()];
        for (name, _, c) in self.jni_params(m) {
            params.push(format!("{c} {name}"));
        }
        let mut pre = String::from("    (void)env;\n    (void)cls;\n");
        let mut post = String::new();
        let mut args = Vec::new();
        if let Some(mutable) = m.receiver {
            let constness = if mutable { "" } else { "const " };
            args.push(format!("({constness}{}*)(intptr_t)self", def.name));
        }
        for p in &m.params {
            let name = lower_camel(&p.name);
            match &p.ty {
                Ty::Prim(prim) => args.push(format!("({})({name})", prim.c())),
                Ty::Enum(e) => args.push(format!("({e})({name})")),
                Ty::Struct(s) => args.push(self.c_struct(s, std::slice::from_ref(&name))),
                Ty::Opaque {
                    name: ty, mutable, ..
                } => {
                    let constness = if *mutable { "" } else { "const " };
                    args.push(format!("({constness}{ty}*)(intptr_t)({name})"));
                }
                Ty::Str => {
                    writeln!(
                        pre,
                        "    jbyte* {name}_bytes = (*env)->GetByteArrayElements(env, {name}, NULL);\n    if (!{name}_bytes) return{};\n    DiplomatStringView {name}_view = {{ (const char*){name}_bytes, (size_t)(*env)->GetArrayLength(env, {name}) }};",
                        error_value(c_ret)
                    )
                    .unwrap();
                    writeln!(
                        post,
                        "    (*env)->ReleaseByteArrayElements(env, {name}, {name}_bytes, JNI_ABORT);"
                    )
                    .unwrap();
                    args.push(format!("{name}_view"));
                }
                Ty::Slice(prim) => {
                    let j = JniPrim::of(*prim);
                    let (_, _, infix) = j.array();
                    writeln!(
                        pre,
                        "    {c}* {name}_items = (*env)->Get{infix}ArrayElements(env, {name}, NULL);\n    if (!{name}_items) return{};\n    Diplomat{d}View {name}_view = {{ (const {pc}*){name}_items, (size_t)(*env)->GetArrayLength(env, {name}) }};",
                        error_value(c_ret),
                        c = j.c(),
                        d = prim.derived(),
                        pc = prim.c()
                    )
                    .unwrap();
                    writeln!(
                        post,
                        "    (*env)->Release{infix}ArrayElements(env, {name}, {name}_items, JNI_ABORT);"
                    )
                    .unwrap();
                    args.push(format!("{name}_view"));
                }
                Ty::Callback => {
                    writeln!(
                        pre,
                        "    DiplomatCallback_{abi}_{raw} {name}_callback = {{ (const void*)(*env)->NewGlobalRef(env, {name}), callback_run, callback_destroy }};",
                        abi = m.abi,
                        raw = p.name
                    )
                    .unwrap();
                    args.push(format!("{name}_callback"));
                }
            }
        }
        if m.ret == Ret::Write {
            pre += "    DiplomatWrite* write = diplomat_buffer_write_create(0);\n";
            args.push("write".into());
        }
        let call = format!("{}({})", m.abi, args.join(", "));
        let mut body = pre;
        let value = |out: &mut String, expr: &str| match &m.ret {
            Ret::Unit => {}
            Ret::Write => out.push_str("    return write_to_bytes(env, write);\n"),
            Ret::Value(ty) => out.push_str(&format!("    return {};\n", self.c_return(ty, expr))),
        };
        match &m.fail {
            Fail::Never => {
                if m.ret == Ret::Unit || m.ret == Ret::Write {
                    writeln!(body, "    {call};").unwrap();
                    body += &post;
                    value(&mut body, "");
                } else {
                    writeln!(body, "    {} result = {call};", self.c_value_type(m)).unwrap();
                    body += &post;
                    value(&mut body, "result");
                }
            }
            fail => {
                writeln!(body, "    {}_result result = {call};", m.abi).unwrap();
                body += &post;
                let throw = match fail {
                    Fail::Enum(e) => format!("throw_{e}(env, result.err)"),
                    _ => format!("throw_unit(env, \"{}::{} failed\")", def.name, m.name),
                };
                let cleanup = if m.ret == Ret::Write {
                    "        diplomat_buffer_write_destroy(write);\n"
                } else {
                    ""
                };
                writeln!(
                    body,
                    "    if (!result.is_ok) {{\n{cleanup}        {throw};\n        return{};\n    }}",
                    error_value(c_ret)
                )
                .unwrap();
                value(&mut body, "result.ok");
            }
        }
        format!(
            "\nJNIEXPORT {c_ret} JNICALL {jni_prefix}{}({}) {{\n{body}}}\n",
            jni_mangle(&self.external(&m.abi)),
            params.join(", ")
        )
    }

    /// The C type an infallible call returns.
    fn c_value_type(&self, m: &Method) -> String {
        match &m.ret {
            Ret::Value(ty) => match ty {
                Ty::Prim(p) => p.c().into(),
                Ty::Enum(n) | Ty::Struct(n) => n.clone(),
                Ty::Opaque { name, .. } => format!("{name}*"),
                Ty::Slice(p) => format!("Diplomat{}View", p.derived()),
                Ty::Str | Ty::Callback => unreachable!(),
            },
            _ => unreachable!("only values are kept"),
        }
    }

    /// A C designated initializer for a struct from flattened JNI
    /// parameters.
    fn c_struct(&self, name: &str, prefix: &[String]) -> String {
        let fields: Vec<String> = self
            .api
            .fields(name)
            .iter()
            .map(|f| {
                let mut path = prefix.to_vec();
                path.push(f.name.clone());
                let leaf = path.join("_");
                let value = match &f.ty {
                    Ty::Prim(p) => format!("({})({leaf})", p.c()),
                    Ty::Enum(e) => format!("({e})({leaf})"),
                    Ty::Struct(s) => self.c_struct(s, &path),
                    _ => unreachable!(),
                };
                format!(".{} = {value}", f.name)
            })
            .collect();
        format!("({name}){{ {} }}", fields.join(", "))
    }

    /// A C expression converting a C value to what the JNI function
    /// returns.
    fn c_return(&self, ty: &Ty, expr: &str) -> String {
        match ty {
            Ty::Prim(p) => c_to_jni(*p, expr),
            Ty::Enum(_) => format!("(jint)({expr})"),
            Ty::Opaque { .. } => format!("(jlong)(intptr_t)({expr})"),
            Ty::Struct(s) => {
                let leaves: Vec<String> = self
                    .leaves(vec![], ty)
                    .into_iter()
                    .map(|(path, leaf)| {
                        let access = format!("({expr}).{}", path.join("."));
                        match leaf {
                            Ty::Prim(p) => c_to_jni(p, &access),
                            Ty::Enum(_) => format!("(jint)({access})"),
                            _ => unreachable!(),
                        }
                    })
                    .collect();
                format!(
                    "(*env)->CallStaticObjectMethod(env, g_native, g_new_{s}{}{})",
                    if leaves.is_empty() { "" } else { ", " },
                    leaves.join(", ")
                )
            }
            Ty::Slice(p) => format!(
                "new_{}_array(env, ({expr}).data, ({expr}).len)",
                p.derived()
            ),
            Ty::Str | Ty::Callback => unreachable!(),
        }
    }
}

/// What a JNI function returns after throwing.
fn error_value(c_ret: &str) -> &'static str {
    match c_ret {
        "void" => "",
        "jobject" | "jbyteArray" | "jbooleanArray" | "jshortArray" | "jintArray" | "jlongArray"
        | "jfloatArray" | "jdoubleArray" => " NULL",
        _ => " 0",
    }
}

trait PipeDoc {
    /// Wraps comment lines in `/** … */`, or nothing when empty.
    fn pipe_doc(self, indent: &str) -> String;
}

impl PipeDoc for String {
    fn pipe_doc(self, indent: &str) -> String {
        if self.trim().is_empty() {
            String::new()
        } else {
            format!("{indent}/**\n{self}{indent} */\n")
        }
    }
}
