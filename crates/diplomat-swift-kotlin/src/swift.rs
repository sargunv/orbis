//! Swift over the C header: a file per type and a file of helpers.
//!
//! The C module's types are always named through the module
//! (`Lib.Camera`), since the Swift types of the same names shadow them.

use std::fmt::Write;

use crate::model::{Api, Def, Fail, Kind, Method, Prim, Ret, Thread, Ty};
use crate::names::{comment, lower_camel, lower_first};
use crate::{Files, SwiftConfig};

const HEADER: &str = "// Generated by diplomat-swift-kotlin. Do not edit.\n";

pub(crate) fn emit(api: &Api, config: &SwiftConfig) -> Result<Files, Vec<String>> {
    let s = Swift {
        api,
        c: &config.c_module,
    };
    let mut files = Files::new();
    for def in &api.defs {
        files.insert(format!("{}.swift", def.name), s.def(def));
    }
    for error in api.errors() {
        files.insert(format!("{error}Failure.swift"), s.failure(error));
    }
    files.insert("DiplomatSupport.swift".into(), s.support());
    Ok(files)
}

struct Swift<'a> {
    api: &'a Api,
    c: &'a str,
}

const KEYWORDS: &[&str] = &[
    "associatedtype",
    "class",
    "deinit",
    "enum",
    "extension",
    "func",
    "import",
    "init",
    "inout",
    "internal",
    "let",
    "operator",
    "private",
    "protocol",
    "public",
    "static",
    "struct",
    "subscript",
    "typealias",
    "var",
    "break",
    "case",
    "continue",
    "default",
    "defer",
    "do",
    "else",
    "fallthrough",
    "for",
    "guard",
    "if",
    "in",
    "repeat",
    "return",
    "switch",
    "where",
    "while",
    "as",
    "catch",
    "false",
    "is",
    "nil",
    "rethrows",
    "super",
    "self",
    "Self",
    "throw",
    "throws",
    "true",
    "try",
];

fn ident(name: &str) -> String {
    escape(lower_camel(name))
}

fn escape(name: String) -> String {
    if KEYWORDS.contains(&name.as_str()) {
        format!("`{name}`")
    } else {
        name
    }
}

/// The public Swift type of a scalar.
fn swift_prim(p: Prim) -> &'static str {
    match p {
        Prim::Bool => "Bool",
        Prim::I8 => "Int8",
        Prim::U8 => "UInt8",
        Prim::I16 => "Int16",
        Prim::U16 => "UInt16",
        Prim::I32 => "Int32",
        Prim::U32 => "UInt32",
        Prim::I64 => "Int64",
        Prim::U64 => "UInt64",
        Prim::Isize => "Int",
        Prim::Usize => "UInt",
        Prim::F32 => "Float",
        Prim::F64 => "Double",
    }
}

/// Swift value to the type the C header imports (`size_t` is `Int`).
fn prim_to_c(p: Prim, expr: &str) -> String {
    match p {
        Prim::Usize => format!("Int(bitPattern: {expr})"),
        _ => expr.to_owned(),
    }
}

fn prim_from_c(p: Prim, expr: &str) -> String {
    match p {
        Prim::Usize => format!("UInt(bitPattern: {expr})"),
        _ => expr.to_owned(),
    }
}

fn doc(docs: &str, indent: &str) -> String {
    comment(docs, "/// ", indent)
}

impl Swift<'_> {
    fn public_type(&self, ty: &Ty) -> String {
        match ty {
            Ty::Prim(p) => swift_prim(*p).into(),
            Ty::Enum(n) | Ty::Struct(n) => n.clone(),
            Ty::Opaque { name, optional, .. } => {
                format!("{name}{}", if *optional { "?" } else { "" })
            }
            Ty::Str => "String".into(),
            Ty::Slice(p) => format!("[{}]", swift_prim(*p)),
            Ty::Callback => "@escaping @Sendable () -> Void".into(),
        }
    }

    fn thread(&self, name: &str) -> Thread {
        match &self.api.def(name).kind {
            Kind::Opaque { thread, .. } => *thread,
            _ => Thread::Any,
        }
    }

    /// A Swift value as the C type.
    fn swift_to_c(&self, ty: &Ty, expr: &str) -> String {
        match ty {
            Ty::Prim(p) => prim_to_c(*p, expr),
            Ty::Enum(e) => format!("{}.{e}(rawValue: numericCast({expr}.rawValue))", self.c),
            Ty::Struct(_) => format!("{expr}.c"),
            Ty::Opaque {
                name,
                optional: true,
                ..
            } => format!("{expr}?.{}", self.access(name)),
            Ty::Opaque { name, .. } => format!("{expr}.{}", self.access(name)),
            Ty::Str | Ty::Slice(_) | Ty::Callback => unreachable!("passed through a closure"),
        }
    }

    /// How a method reaches an object's handle: checking the thread for
    /// owner-thread types.
    fn access(&self, name: &str) -> &'static str {
        match self.thread(name) {
            Thread::Owner => "live()",
            Thread::Any => "handle",
        }
    }

    /// A C value as the Swift type.
    fn c_to_swift(&self, ty: &Ty, expr: &str) -> String {
        match ty {
            Ty::Prim(p) => prim_from_c(*p, expr),
            Ty::Enum(e) => format!("{e}(rawValue: numericCast({expr}.rawValue))!"),
            Ty::Struct(s) => format!("{s}({expr})"),
            Ty::Opaque {
                name,
                optional: true,
                ..
            } => format!("{expr}.map {{ {name}(handle: $0) }}"),
            Ty::Opaque { name, .. } => format!("{name}(handle: {expr}!)"),
            Ty::Slice(_) => format!("copySlice({expr})"),
            Ty::Str | Ty::Callback => unreachable!("not a return type"),
        }
    }

    fn def(&self, def: &Def) -> String {
        let mut out = format!(
            "{HEADER}\n#if canImport(Darwin)\nimport Darwin\n#elseif canImport(Glibc)\nimport Glibc\n#endif\nimport {}\n\n",
            self.c
        );
        match &def.kind {
            Kind::Enum { variants } => {
                out += &doc(&def.docs, "");
                writeln!(
                    out,
                    "public enum {}: Int, Sendable, CaseIterable {{",
                    def.name
                )
                .unwrap();
                for (name, value, docs) in variants {
                    out += &doc(docs, "    ");
                    writeln!(out, "    case {} = {value}", escape(lower_first(name))).unwrap();
                }
                if !def.methods.is_empty() {
                    out += "\n";
                }
                for m in &def.methods {
                    out += &self.method(def, m, "    ");
                }
                out += "}\n";
            }
            Kind::Struct { fields } => {
                out += &doc(&def.docs, "");
                writeln!(out, "public struct {}: Equatable, Sendable {{", def.name).unwrap();
                for f in fields {
                    out += &doc(&f.docs, "    ");
                    writeln!(
                        out,
                        "    public var {}: {}",
                        ident(&f.name),
                        self.public_type(&f.ty)
                    )
                    .unwrap();
                }
                let params: Vec<String> = fields
                    .iter()
                    .map(|f| format!("{}: {}", ident(&f.name), self.public_type(&f.ty)))
                    .collect();
                writeln!(out, "\n    public init({}) {{", params.join(", ")).unwrap();
                for f in fields {
                    let name = ident(&f.name);
                    writeln!(out, "        self.{0} = {0}", name.trim_matches('`')).unwrap();
                }
                out += "    }\n\n";
                writeln!(out, "    init(_ c: {}.{}) {{", self.c, def.name).unwrap();
                for f in fields {
                    writeln!(
                        out,
                        "        self.{} = {}",
                        lower_camel(&f.name),
                        self.c_to_swift(&f.ty, &format!("c.{}", f.name))
                    )
                    .unwrap();
                }
                out += "    }\n\n";
                writeln!(out, "    var c: {}.{} {{", self.c, def.name).unwrap();
                let args: Vec<String> = fields
                    .iter()
                    .map(|f| {
                        format!(
                            "{}: {}",
                            f.name,
                            self.swift_to_c(&f.ty, &format!("self.{}", lower_camel(&f.name)))
                        )
                    })
                    .collect();
                writeln!(
                    out,
                    "        {}.{}({})\n    }}",
                    self.c,
                    def.name,
                    args.join(", ")
                )
                .unwrap();
                for m in &def.methods {
                    out += "\n";
                    out += &self.method(def, m, "    ");
                }
                out += "}\n";
            }
            Kind::Opaque { destroy, thread } => {
                let mut docs = def.docs.clone();
                docs += match thread {
                    Thread::Owner => {
                        "\n\nUse it only on the thread that created it, and release it there."
                    }
                    Thread::Any => "\n\nIt may be used on any thread.",
                };
                out += &doc(docs.trim_start(), "");
                let sendable = match thread {
                    Thread::Owner => "",
                    Thread::Any => ": @unchecked Sendable",
                };
                writeln!(out, "public final class {}{sendable} {{", def.name).unwrap();
                out += "    let handle: OpaquePointer\n";
                if *thread == Thread::Owner {
                    out += "    private let owner = pthread_self()\n";
                }
                out +=
                    "\n    init(handle: OpaquePointer) {\n        self.handle = handle\n    }\n\n";
                if *thread == Thread::Owner {
                    // Releasing the last reference elsewhere would destroy
                    // the object under its owner's feet.
                    writeln!(
                        out,
                        "    deinit {{\n        precondition(\n            pthread_equal(owner, pthread_self()) != 0,\n            \"{} is released on a thread other than the one that created it\"\n        )\n        {destroy}(handle)\n    }}\n",
                        def.name
                    )
                    .unwrap();
                } else {
                    writeln!(out, "    deinit {{\n        {destroy}(handle)\n    }}\n").unwrap();
                }
                if *thread == Thread::Owner {
                    writeln!(
                        out,
                        "    func live() -> OpaquePointer {{\n        precondition(\n            pthread_equal(owner, pthread_self()) != 0,\n            \"{} is used on a thread other than the one that created it\"\n        )\n        return handle\n    }}\n",
                        def.name
                    )
                    .unwrap();
                }
                for m in &def.methods {
                    out += &self.method(def, m, "    ");
                }
                out += "}\n";
            }
        }
        out
    }

    fn method(&self, def: &Def, m: &Method, indent: &str) -> String {
        let mut docs = m.docs.clone();
        if let Some(category) = &m.category {
            if !docs.is_empty() {
                docs += "\n\n";
            }
            write!(docs, "Contract: `{category}`.").unwrap();
        }
        if let Fail::Enum(e) = &m.fail {
            write!(docs, "\n\n- Throws: `{e}Failure` when it fails.").unwrap();
        }
        let mut out = doc(&docs, indent);
        let params: Vec<String> = m
            .params
            .iter()
            .map(|p| format!("{}: {}", ident(&p.name), self.public_type(&p.ty)))
            .collect();
        let ret = match &m.ret {
            Ret::Unit => String::new(),
            Ret::Write => " -> String".into(),
            Ret::Value(ty) => format!(" -> {}", self.public_type(ty)),
        };
        let throws = if m.fail == Fail::Never { "" } else { " throws" };
        let statik = if m.receiver.is_none() { "static " } else { "" };
        writeln!(
            out,
            "{indent}public {statik}func {}({}){throws}{ret} {{",
            ident(&m.name),
            params.join(", ")
        )
        .unwrap();

        // Arguments; strings, slices and text out go through closures.
        let mut args = Vec::new();
        if m.receiver.is_some() {
            args.push(match self.thread(&def.name) {
                Thread::Owner => "live()".to_owned(),
                Thread::Any => "handle".to_owned(),
            });
        }
        let mut wrappers = Vec::new();
        let mut setup = Vec::new();
        for p in &m.params {
            let name = ident(&p.name);
            let bare = name.trim_matches('`').to_owned();
            match &p.ty {
                Ty::Str => {
                    wrappers.push(format!("withStringView({name}) {{ {bare}View in"));
                    args.push(format!("{bare}View"));
                }
                Ty::Slice(_) => {
                    wrappers.push(format!("withSliceView({name}) {{ {bare}View in"));
                    args.push(format!("{bare}View"));
                }
                Ty::Callback => {
                    setup.push(format!(
                        "let {bare}Box = Unmanaged.passRetained(CallbackBox({name})).toOpaque()"
                    ));
                    args.push(format!(
                        "{}.DiplomatCallback_{}_{}(data: UnsafeRawPointer({bare}Box), run_callback: {{ CallbackBox.run($0) }}, destructor: {{ CallbackBox.release($0) }})",
                        self.c, m.abi, p.name
                    ));
                }
                ty => args.push(self.swift_to_c(ty, &name)),
            }
        }
        if m.ret == Ret::Write {
            wrappers.push("withWrite { write in".into());
            args.push("write".into());
        }
        let mut call = format!("{}({})", m.abi, args.join(", "));
        for w in wrappers.iter().rev() {
            call = format!("{w} {call} }}");
        }
        for line in &setup {
            writeln!(out, "{indent}    {line}").unwrap();
        }
        let failure = |out: &mut String| match &m.fail {
            Fail::Never => {}
            Fail::Unit => writeln!(
                out,
                "{indent}    guard result.is_ok else {{ throw DiplomatCallFailure(call: \"{}\") }}",
                m.abi
            )
            .unwrap(),
            Fail::Enum(e) => {
                let message = match &self.api.error_messages[e] {
                    Some(f) => format!("{e}.{}()", lower_camel(f)),
                    None => format!("\"\\({e}(rawValue: numericCast(result.err.rawValue))!)\""),
                };
                writeln!(
                    out,
                    "{indent}    guard result.is_ok else {{\n{indent}        throw {e}Failure(error: {e}(rawValue: numericCast(result.err.rawValue))!, message: {message})\n{indent}    }}"
                )
                .unwrap()
            }
        };
        match (&m.ret, &m.fail) {
            (Ret::Unit, Fail::Never) => writeln!(out, "{indent}    {call}").unwrap(),
            (Ret::Unit, _) => {
                writeln!(out, "{indent}    let result = {call}").unwrap();
                failure(&mut out);
            }
            (Ret::Write, Fail::Never) => writeln!(out, "{indent}    return {call}.text").unwrap(),
            (Ret::Write, _) => {
                writeln!(out, "{indent}    let (result, text) = {call}.pair").unwrap();
                failure(&mut out);
                writeln!(out, "{indent}    return text").unwrap();
            }
            (Ret::Value(ty), Fail::Never) => {
                writeln!(out, "{indent}    return {}", self.c_to_swift(ty, &call)).unwrap()
            }
            (Ret::Value(ty), _) => {
                writeln!(out, "{indent}    let result = {call}").unwrap();
                failure(&mut out);
                writeln!(
                    out,
                    "{indent}    return {}",
                    self.c_to_swift(ty, "result.ok")
                )
                .unwrap();
            }
        }
        writeln!(out, "{indent}}}\n").unwrap();
        out
    }

    fn failure(&self, error: &str) -> String {
        format!(
            "{HEADER}\n/// A call failed with `{error}` `error`; `message` says why.\npublic struct {error}Failure: Error, CustomStringConvertible, Sendable {{\n    public let error: {error}\n    public let message: String\n\n    public var description: String {{\n        \"\\(error): \\(message)\"\n    }}\n}}\n"
        )
    }

    fn support(&self) -> String {
        format!(
            r#"{HEADER}
import {c}

/// A call whose error carries no value failed.
public struct DiplomatCallFailure: Error, Sendable {{
    public let call: String
}}

/// UTF-8 text as a string view for the length of `body`.
func withStringView<R>(_ text: String, _ body: ({c}.DiplomatStringView) -> R) -> R {{
    var text = text
    return text.withUTF8 {{ bytes in
        body({c}.DiplomatStringView(
            data: bytes.baseAddress.map {{ UnsafeRawPointer($0).assumingMemoryBound(to: CChar.self) }},
            len: bytes.count
        ))
    }}
}}

/// Text written through a `DiplomatWrite`, with the call's result.
struct Written<R> {{
    let pair: (R, String)
    var text: String {{ pair.1 }}
}}

func withWrite<R>(_ body: (UnsafeMutablePointer<{c}.DiplomatWrite>) -> R) -> Written<R> {{
    let write = diplomat_buffer_write_create(0)!
    defer {{ diplomat_buffer_write_destroy(write) }}
    let result = body(write)
    let bytes = UnsafeRawBufferPointer(
        start: diplomat_buffer_write_get_bytes(write),
        count: diplomat_buffer_write_len(write)
    )
    return Written(pair: (result, String(decoding: bytes, as: UTF8.self)))
}}

/// A callback kept by the library and called from any thread.
final class CallbackBox {{
    let run: @Sendable () -> Void

    init(_ run: @escaping @Sendable () -> Void) {{
        self.run = run
    }}

    static func run(_ data: UnsafeRawPointer?) {{
        Unmanaged<CallbackBox>.fromOpaque(data!).takeUnretainedValue().run()
    }}

    static func release(_ data: UnsafeRawPointer?) {{
        Unmanaged<CallbackBox>.fromOpaque(data!).release()
    }}
}}
{slices}"#,
            c = self.c,
            slices = self.slice_support()
        )
    }

    /// `withSliceView` and `copySlice` for the scalar types slices use.
    fn slice_support(&self) -> String {
        let mut prims: Vec<Prim> = Vec::new();
        let mut out_prims: Vec<Prim> = Vec::new();
        for def in &self.api.defs {
            for m in &def.methods {
                for p in &m.params {
                    if let Ty::Slice(p) = p.ty
                        && !prims.contains(&p)
                    {
                        prims.push(p);
                    }
                }
                if let Ret::Value(Ty::Slice(p)) = m.ret
                    && !out_prims.contains(&p)
                {
                    out_prims.push(p);
                }
            }
        }
        let mut out = String::new();
        for p in prims {
            let view = format!("{}.Diplomat{}View", self.c, p.derived());
            let t = swift_prim(p);
            write!(
                out,
                "\nfunc withSliceView<R>(_ items: [{t}], _ body: ({view}) -> R) -> R {{\n    items.withUnsafeBufferPointer {{ buffer in\n        body({view}(data: {data}, len: buffer.count))\n    }}\n}}\n",
                data = if p == Prim::Usize {
                    "buffer.baseAddress.map { UnsafeRawPointer($0).assumingMemoryBound(to: Int.self) }".to_owned()
                } else {
                    "buffer.baseAddress".to_owned()
                }
            )
            .unwrap();
        }
        for p in out_prims {
            let view = format!("{}.Diplomat{}View", self.c, p.derived());
            let t = swift_prim(p);
            let element = if p == Prim::Usize {
                "UInt(bitPattern: $0)"
            } else {
                "$0"
            };
            write!(
                out,
                "\nfunc copySlice(_ view: {view}) -> [{t}] {{\n    guard let data = view.data, view.len > 0 else {{ return [] }}\n    return UnsafeBufferPointer(start: data, count: view.len).map {{ {element} }}\n}}\n"
            )
            .unwrap();
        }
        out
    }
}
