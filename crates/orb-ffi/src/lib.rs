//! [maplibre-native-ffi](https://github.com/maplibre/maplibre-native-ffi)'s
//! C API on `orb-api`: the `maplibre-native-c` library that mln-ffi's
//! bindings link or load, so they draw with Orbis instead of MapLibre
//! Native. mln-rs owns the API's headers and its C ABI suite; `cargo xtask
//! mln-ffi` scores this library against that suite at the mln-rs commit
//! `xtask/src/mln_ffi.rs` pins.
//!
//! Each runtime is a thread that runs its maps' commands, as mln-ffi's core
//! worker does, and each render session a thread that draws its map. Calls
//! check their arguments on the caller's thread, post their work to the
//! thread that does it, and report through their `mln_completion` once,
//! whatever becomes of the work: work dropped unrun reports
//! `MLN_STATUS_CANCELLED`, and a panic on a runtime or session thread fails
//! the work it was doing while the thread goes on. Handles are 64-bit ids,
//! so a stale or foreign one is an error, never a dangling pointer.
//!
//! The declarations are bindgen's reading of the pinned headers (`sys`),
//! and every function this crate doesn't implement is a stub in `stubs.rs`
//! that returns `MLN_STATUS_UNSUPPORTED`, both generated by `cargo xtask
//! mln-ffi declarations`.

